'use strict';
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const path = require('node:path');
const base = 'http://127.0.0.1:' + (process.env.PORT || 3111);
(async () => {
  const browser = await chromium.launch({ headless: true, channel: process.env.WF_BROWSER_CHANNEL || 'msedge' });
  let passed = 0;
  const check = (name, value) => { assert.ok(value, name); console.log('PASS ' + name); passed++; };
  try {
    const errors = [];
    const session = async username => {
      const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
      const page = await context.newPage(); page.on('pageerror', e => errors.push(e.message));
      await page.goto(base); await page.fill('#lu', username); await page.fill('#lp', 'Track@2026');
      await page.click('button[type=submit]'); await page.waitForSelector('.shell');
      return { context, page };
    };
    const logger = await session('mpaling');
    const state = async () => (await (await logger.context.request.get(base + '/api/state')).json()).state;
    const before = (await state()).docs.length;
    const p = logger.page;
    await p.click('[data-act=newDoc]');
    await p.click('#btnFwd'); await p.waitForSelector('.toast.bad');
    check('empty log form refuses to create a document', (await state()).docs.length === before);
    await p.selectOption('[data-form=doc] select[name=commType]', 'Letter');
    await p.fill('[data-form=doc] input[name=source]', 'Mock Regional Office');
    await p.fill('[data-form=doc] textarea[name=subject]', 'MOCK UI — October inspection compliance');
    await p.selectOption('[data-form=doc] select[name=docType]', 'External Communication');
    await p.selectOption('[data-form=doc] select[name=division]', 'CMED');
    await p.fill('[data-form=doc] input[name=refNo]', 'MOCK-UI-2026-001');
    await p.click('#btnFwd'); await p.waitForFunction(() => !document.querySelector('[data-form=doc]'));
    const doc = (await state()).docs.find(d => d.refNo === 'MOCK-UI-2026-001');
    check('browser log creates and forwards exactly one mock document', !!doc && doc.status === 'at_focal' && (await state()).docs.length === before + 1);
    const focal = await session('acabrera'), staff = await session('dcruz'), manager = await session('mmartinez'), dept = await session('ohanova'), unrelated = await session('jtanguilig');
    const open = async s => { await s.page.goto(base + '/#/doc/' + doc.id); await s.page.reload(); await s.page.waitForSelector('.pagehead h1'); await s.page.waitForSelector('#splash', { state: 'detached' }); };
    const stage = async (s, status) => { await s.page.waitForFunction(({id,status}) => S.docs.find(d => d.id === id)?.status === status, {id:doc.id,status}); check(status + ' saved', (await state()).docs.find(d => d.id === doc.id).status === status); };
    await open(unrelated);
    check('unrelated staff can view without assign, review or release controls', await unrelated.page.locator('[data-act=doAssign], [data-act=doSubmit], [data-act=doReview], [data-act=doLogout]').count() === 0);
    await open(focal);
    await focal.page.selectOption('select[name=txType]', 'Simple Transaction');
    await focal.page.selectOption('#assigneeSel', 'cruz');
    await focal.page.click('[data-act=doAssign]'); await stage(focal, 'processing');
    await open(staff); await staff.page.selectOption('select[name=reviewer]', 'cabrera');
    await staff.page.click('[data-act=doSubmit]'); await stage(staff, 'sup_review');
    const review = async (s, type, status, text) => {
      await open(s); const button = s.page.locator('[data-act=doReview][data-type="' + type + '"]');
      if (text) await button.locator('xpath=ancestor::*[@data-panel]').locator('textarea[name=text]').fill(text);
      await button.click(); await stage(s, status);
    };
    await review(focal, 'sup_return', 'compliance', 'Please include the inspection checklist');
    await open(staff); await staff.page.click('[data-act=doSubmit]'); await staff.page.waitForSelector('.toast.bad');
    check('empty compliance is rejected and remains at staff', (await state()).docs.find(d => d.id === doc.id).status === 'compliance');
    await staff.page.locator('[data-act=doSubmit]').locator('xpath=ancestor::*[@data-panel]').locator('textarea[name=text]').fill('Inspection checklist included');
    await staff.page.click('[data-act=doSubmit]'); await stage(staff, 'sup_review');
    await review(focal, 'sup_approve', 'div_review'); await review(manager, 'div_approve', 'dept_review'); await review(dept, 'dept_clear', 'cleared');
    await open(logger); await p.fill('input[name=outTo]', 'Mock Records Office'); await p.click('[data-act=doLogout]'); await stage(logger, 'out');
    const completed = (await state()).docs.find(d => d.id === doc.id);
    check('history retains compliance response and release destination', completed.cycles === 1 && completed.outTo === 'Mock Records Office' && completed.comments.some(c => c.resolved && c.response === 'Inspection checklist included'));
    await p.screenshot({ path: path.join(process.env.SHOTS, 'mock-document-completed.png'), fullPage: true });
    await p.reload(); await p.waitForSelector('.pagehead h1');
    check('completed document survives reload', await p.locator('.pagehead h1').innerText() === completed.subject);
    check('no browser JavaScript errors', errors.length === 0);
    console.log(passed + ' passed, 0 failed');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
